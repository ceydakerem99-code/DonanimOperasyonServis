import CoreGraphics

/// Corner radius tokens.
enum AppRadius {
    /// 12 pt — cards, primary buttons, form fields.
    static let card: CGFloat = 12
    /// 8 pt — chips, small pills.
    static let chip: CGFloat = 8
    /// 20 pt — bottom sheets and modal top corners.
    static let sheet: CGFloat = 20
    /// 8 pt — image thumbnails, photo cells.
    static let image: CGFloat = 8
}
